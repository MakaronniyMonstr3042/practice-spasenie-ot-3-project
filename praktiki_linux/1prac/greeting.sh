
#!/usr/bin/env bash

# Запрашиваем ФИО и группу пользователя
read -r -p "Введите ваше ФИО_ГРУППА: " name

# Проверяем, что пользователь что-нибудь ввёл
if [[ -z "$name" ]]; then
    echo "Ошибка: поле не должно быть пустым."
    exit 1
fi

# Выводим приветствие
echo "Привет, $name! Добро пожаловать в мир Bash!"

