#!/bin/bash
# Выводит информацию о системе

# Имя хоста
echo "=== Имя хоста ==="
hostname

# Версия ядра
echo
echo "=== Версия ядра ==="
uname -r

# Свободная память
echo
echo "=== Информация об оперативной памяти ==="
